"""Generate kv_vectors.h: AES-GCM-SIV reference tags from an independent
implementation (python3-cryptography, i.e. OpenSSL).

Inputs are deterministic byte patterns that test_verifier.c regenerates, so
only parameters and expected outputs are stored.   Usage: ./gen_vectors.py > kv_vectors.h
"""
import struct
import sys

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESGCMSIV

LENGTHS = [0, 1, 15, 16, 17, 31, 32, 33, 112, 127, 128, 129, 143, 144, 255, 256,
           1000, 4096, 16383, 16384, 16400]


def pat(n, mul, j, add):
    return bytes((i * mul + j * add + 1) & 0xFF for i in range(n))


def key_of(j, klen):
    return bytes((i * 29 + j * 101 + 7) & 0xFF for i in range(klen))


def nonce_of(j):
    return bytes((i * 47 + j * 13 + 3) & 0xFF for i in range(12))


def fnv1a32(name):
    h = 2166136261
    for c in name.encode():
        h = ((h ^ c) * 16777619) & 0xFFFFFFFF
    return h


def hexs(b):
    return '"' + b.hex() + '"'


out = sys.stdout
out.write("/* Generated by gen_vectors.py from python3-cryptography (OpenSSL). Do not edit. */\n")

# AES known answers (FIPS-197 appendix C inputs)
out.write("static const struct { int klen; const char *ct; } AES_KAT[] = {\n")
for klen in (16, 32):
    enc = Cipher(algorithms.AES(bytes(range(klen))), modes.ECB()).encryptor()
    ct = enc.update(bytes.fromhex("00112233445566778899aabbccddeeff")) + enc.finalize()
    out.write("\t{ %d, %s },\n" % (klen, hexs(ct)))
out.write("};\n\n")

# AES-GCM-SIV tags of (aad pattern, empty plaintext)
out.write("static const struct { int j, klen; unsigned len; const char *tag; } SIV_KAT[] = {\n")
j = 0
for klen in (16, 32):
    for n in LENGTHS:
        aad = pat(n, 167, j, 59)
        tag = AESGCMSIV(key_of(j, klen)).encrypt(nonce_of(j), b"", aad)
        out.write("\t{ %d, %d, %d, %s },\n" % (j, klen, n, hexs(tag)))
        j += 1
out.write("};\n\n")

# Frame tags: default nonce, AAD = location block || payload
FRAMES = [(1, 0x30000, 16384, 24408304, "ktext"),
          (2, 0, 3776, 3776, "sys_call_table"),
          (4, 0x4000, 100, 0x4064, "ext4")]
out.write("static const struct { unsigned type, off, len, seglen; const char *name, *tag; } FRAME_KAT[] = {\n")
for idx, (typ, off, n, seglen, name) in enumerate(FRAMES):
    loc = struct.pack("<IIII", typ, off, seglen, fnv1a32(name))
    payload = pat(n, 211, idx, 17)
    tag = AESGCMSIV(key_of(100, 32)).encrypt(b"KIM-FRAME-v1", b"", loc + payload)
    out.write("\t{ %d, %d, %d, %d, \"%s\", %s },\n" % (typ, off, n, seglen, name, hexs(tag)))
out.write("};\n")
